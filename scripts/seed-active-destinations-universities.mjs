async function main() {
  const existing = await prisma.university.findMany({ select: { slug: true } });
  const existingSlugs = new Set(existing.map((u) => u.slug));

  let created = 0;
  let skipped = 0;

  for (const u of UNIVERSITIES) {
    if (existingSlugs.has(u.slug)) {
      skipped += 1;
      continue;
    }

    const majors = u.programs.map((p) => p.name).join(', ');

    await prisma.university.create({
      data: {
        slug: u.slug,
        name: u.name,
        location: u.location,
        country: u.country,
        city: u.city,
        intake: u.intake,
        degree: u.degree,
        taught: u.taught,
        majors,
        tuition: u.tuition,
        tuitionDetails: JSON.stringify(u.tuitionDetails),
        documents: JSON.stringify(u.documents),
        deadlineApplication: u.deadlineApplication,
        notes: JSON.stringify(u.notes),
        badges: JSON.stringify(u.badges),
        isActive: true,
        officialUrl: u.officialUrl,
        aliases: JSON.stringify(u.aliases),
        legacySlugs: '[]',
        relationshipType: 'public_direct_application',
        relationshipEvidenceUrl: u.officialUrl,
        recognitionAuthority: u.recognitionAuthority,
        recognitionSourceUrl: u.recognitionSourceUrl,
        sourceUrls: JSON.stringify(u.sourceUrls),
        lastVerifiedAt: VERIFIED_AT,
        verificationExpiresAt: EXPIRES_AT,
        verificationStatus: 'verified',
        programs: {
          create: u.programs.map((p) => ({
            level: p.level,
            name: p.name,
            subject: p.subject,
            languages: p.languages,
            duration: p.duration,
            intakes: p.intakes,
            tuition: p.tuition,
            eligibility: JSON.stringify(u.documents),
            sourceUrl: p.sourceUrl,
            status: 'active',
          })),
        },
        fees: {
          create: u.fees.map((f) => ({
            item: f.item,
            cost: f.cost,
            recipient: f.recipient,
            refundable: f.refundable,
            validFor: '2026/2027 Academic Year',
            sourceUrl: f.sourceUrl,
          })),
        },
        scholarships: {
          create: u.scholarships.map((s) => ({
            title: s.title,
            type: s.type,
            amount: s.amount,
            coverage: s.coverage,
            condition: s.condition,
            renewal: s.renewal,
            deadline: s.deadline,
            eligiblePrograms: JSON.stringify(s.eligiblePrograms),
            details: JSON.stringify([s.coverage, s.condition]),
            sourceUrl: s.sourceUrl,
            status: 'active',
          })),
        },
      },
    });
    created += 1;
  }

  const byCountry = await prisma.university.groupBy({
    by: ['country'],
    where: { isActive: true },
    _count: { _all: true },
    orderBy: { _count: { country: 'desc' } },
  });

  console.log(`\n=== ACTIVE DESTINATIONS EXPANSION COMPLETE ===`);
  console.log(`Target: ${UNIVERSITIES.length} | Created: ${created} | Skipped existing: ${skipped}`);
  console.log(`Active Universities by Country (${byCountry.length} countries):`);
  let total = 0;
  for (const row of byCountry) {
    total += row._count._all;
    console.log(`  - ${row.country}: ${row._count._all}`);
  }
  console.log(`Total Active Universities: ${total}`);
}

main()
  .catch((err) => {
    console.error('Active destinations seed failed:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
