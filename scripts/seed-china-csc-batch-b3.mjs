async function main() {
  let created = 0;
  let skipped = 0;

  for (const u of UNIVERSITIES_WAVE_3) {
    const existing = await prisma.university.findUnique({ where: { slug: u.slug } });
    if (existing) {
      skipped += 1;
      continue;
    }

    const levels = Array.from(new Set(u.programs.map((p) => p.level)));
    const langTokens = Array.from(
      new Set(
        u.programs
          .flatMap((p) => p.languages.split(',').map((s) => s.trim()))
          .filter(Boolean),
      ),
    );

    const fees = [
      {
        item: 'Application Fee',
        cost: u.appFee,
        recipient: `${u.name} (International Admissions Office)`,
        refundable: 'no',
        validFor: 'One-time per application',
        notes: 'Verify fee waiver rules for CSC scholarship applicants on the official university portal',
        sourceUrl: u.officialUrl,
      },
      {
        item: 'Comprehensive Medical Insurance',
        cost: 'CNY 800 / year',
        recipient: 'MoE-Designated Insurance Provider (Ping An / University Portal)',
        refundable: 'no',
        validFor: '1 academic year',
        notes: 'Mandatory for all international students in China; CNY 400 per semester for 1-semester language students',
        sourceUrl: u.officialUrl,
      },
      {
        item: 'Residence Permit',
        cost: 'CNY 400 / year',
        recipient: 'Local Public Security Bureau (PSB)',
        refundable: 'no',
        validFor: 'Per year in China',
        notes: 'Standard statutory annual student residence permit fee in China',
        sourceUrl: u.officialUrl,
      },
    ];

    const scholarships = [
      CSC_SCHOLARSHIP(u.cscAgencyNumber, u.officialUrl, u.cscLevels || ['Bachelor', 'Master', 'PhD']),
      LOCAL_GOV_SCHOLARSHIP(
        u.localScholarship[0],
        u.localScholarship[1],
        u.localScholarship[2],
        u.officialUrl,
        u.localScholarship[3] || ['Bachelor', 'Master', 'PhD'],
        u.localScholarship[4] || 'Partial / Full Tuition',
      ),
    ];

    await prisma.university.create({
      data: {
        slug: u.slug,
        name: u.name,
        chineseName: u.chineseName,
        location: `${u.city}, ${u.province}, China`,
        country: 'China',
        province: u.province,
        city: u.city,
        cscAgencyNumber: u.cscAgencyNumber,
        isCscDesignated: true,
        isMoeMbbsListed: Boolean(u.isMoeMbbsListed),
        intake: 'March, September',
        degree: levels.join(', '),
        taught: langTokens.join(', '),
        majors: u.majors.join(', '),
        tuition: u.tuition,
        tuitionDetails: JSON.stringify(u.programs.map((p) => `${p.level}: ${p.name} — ${p.tuition}`)),
        documents: JSON.stringify(STANDARD_DOCS),
        deadlineApplication: 'March – May (September intake); check CSC portal for Type A/B dates',
        notes: JSON.stringify([
          `Official CSC Designated University (Agency Number: ${u.cscAgencyNumber}).`,
          'Tuition and itemized arrival fees are kept strictly separate; confirm exact room type and intake deadline before payment.',
        ]),
        badges: JSON.stringify(u.badges),
        isActive: true,
        officialUrl: u.officialUrl,
        aliases: JSON.stringify(u.aliases),
        legacySlugs: JSON.stringify([]),
        relationshipType: 'public_direct_application',
        recognitionAuthority: 'Ministry of Education (MoE), PR China · CSC Designated',
        recognitionSourceUrl: 'https://www.campuschina.org/',
        sourceUrls: JSON.stringify([u.officialUrl]),
        lastVerifiedAt: VERIFIED_AT,
        verificationExpiresAt: EXPIRES_AT,
        verificationStatus: 'verified',
        programs: {
          create: u.programs.map((p) => ({
            level: p.level,
            name: p.name,
            subject: p.subject,
            languages: p.languages,
            duration: p.duration,
            intakes: p.intakes,
            tuition: p.tuition,
            applicationDeadline: p.level === 'Language' ? 'Check March / September cycle' : 'Mar – May (check current cycle)',
            eligibility: JSON.stringify(
              p.level === 'Language'
                ? ['High school diploma or equivalent, age 18–50, good health', 'No HSK required for beginner placement']
                : ['Non-Chinese citizen in good health meeting academic GPA & language requirements', 'Check CSCA requirement for undergraduate admission'],
            ),
            sourceUrl: u.officialUrl,
            status: 'active',
          })),
        },
        fees: { create: fees },
        scholarships: { create: scholarships },
      },
    });

    created += 1;
  }

  console.log('=== PHASE 2 BATCH B WAVE 3 COMPLETE ===');
  console.log(`Target universities: ${UNIVERSITIES_WAVE_3.length} | Created: ${created} | Skipped existing: ${skipped}`);
}

main()
  .catch((err) => {
    console.error('seed-china-csc-batch-b3 failed:', err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
