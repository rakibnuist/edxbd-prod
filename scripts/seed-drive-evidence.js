async function main() {
  for (const { universityContains, ...record } of records) {
    const university = universityContains
      ? await prisma.university.findFirst({ where: { name: { contains: universityContains } }, select: { id: true } })
      : null;
    const data = {
      ...record,
      universityId: university?.id || null,
      lastVerifiedAt: checkedOn,
      privacyStatus: 'redacted',
      isPublished: true,
      documentUrl: null,
    };
    const existing = await prisma.evidenceAsset.findFirst({ where: { referenceLabel: record.referenceLabel } });
    if (existing) await prisma.evidenceAsset.update({ where: { id: existing.id }, data });
    else await prisma.evidenceAsset.create({ data });
  }
}

main()
  .then(() => console.log(`Imported ${records.length} privacy safe evidence records.`))
  .finally(() => prisma.$disconnect());
